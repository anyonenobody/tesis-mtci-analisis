#!/usr/bin/env python3
"""
detect_ai_patterns.py - Academic Style & AI Footprint Analyzer
==============================================================
Analyzes text for common AI markers (low burstiness, uniform sentence length,
formulaic transitions, academic clichés) that trigger Turnitin, GPTZero, or CopyLeaks.

Usage:
    uv run python detect_ai_patterns.py "ruta_al_archivo.txt"
    uv run python detect_ai_patterns.py --text "Texto a evaluar..."
"""

import sys
import re
import math
import argparse
from collections import Counter
from typing import TypedDict, Union

# Common AI Spanish buzzwords and cliches
AI_BUZZWORDS = [
    r"\bde creciente relevancia\b",
    r"\ben este escenario\b",
    r"\bno obstante este respaldo\b",
    r"\bandamiaje\b",
    r"\bun tapiz\b",
    r"\bes menester\b",
    r"\bcabe destacar\b",
    r"\besclarecedor(?:a)?\b",
    r"\bdesconexión crítica\b",
    r"\bun vacío crítico\b",
    r"\bfenómeno de creciente\b",
    r"\bconvergen de manera armónica\b",
    r"\bde vital importancia\b",
    r"\bdesempeña un papel fundamental\b",
    r"\bjuega un papel crucial\b",
    r"\ben aras de\b",
    r"\bresulta imperativo\b",
    r"\bun compendio de\b",
    r"\babordaje holístico integral\b",
    r"\ben resumen\b",
    r"\ben conclusión\b",
    r"\bpor consiguiente\b",
    r"\basimismo\b",
]

# Formulaic paragraph starters commonly generated by LLMs
FORMULAIC_STARTERS = [
    r"^(En este sentido|Por un lado|Por otro lado|Asimismo|En primer lugar|En segundo lugar|No obstante|Por consiguiente|En conclusión|Frente a este escenario|Ante esta problemática)",
]


class StatsDict(TypedDict):
    total_words: int
    total_sentences: int
    avg_sentence_length: float
    sentence_std_dev: float
    burstiness_index: float
    lexical_richness_ttr: float


class AnalysisSuccess(TypedDict):
    stats: StatsDict
    buzzwords_found: list[str]
    risk_level: str
    risk_factors: list[str]
    sentences_preview: list[tuple[int, str]]


class AnalysisError(TypedDict):
    error: str


AnalysisResult = Union[AnalysisSuccess, AnalysisError]


def split_sentences(text: str) -> list[str]:
    """Splits text into sentences handling abbreviations and initials."""
    clean_text = re.sub(r"\s+", " ", text).strip()
    # Protect common abbreviations
    protected = clean_text
    abbreviations = [r"No\.", r"art\.", r"pág\.", r"vol\.", r"ed\.", r"et al\.", r"Dr\.", r"Dra\.", r"Lic\."]
    for abb in abbreviations:
        protected = re.sub(abb, abb.replace(".", "@DOT@"), protected, flags=re.IGNORECASE)

    raw_sentences = re.split(r"(?<=[.!?])\s+", protected)
    sentences = []
    for s in raw_sentences:
        s = s.replace("@DOT@", ".").strip()
        if len(s.split()) >= 2:  # ignore 1-word fragments
            sentences.append(s)
    return sentences


def analyze_text(text: str) -> AnalysisResult:
    sentences = split_sentences(text)
    if not sentences:
        return {"error": "No sentences detected"}

    sentence_lengths = [len(s.split()) for s in sentences]
    n_sentences = len(sentences)
    avg_len = sum(sentence_lengths) / n_sentences
    variance = sum((x - avg_len) ** 2 for x in sentence_lengths) / n_sentences
    std_dev = math.sqrt(variance)

    # Burstiness coefficient: high std_dev relative to mean implies human writing
    # AI models typically score std_dev < 6.0 and variance < 35
    burstiness_score = std_dev / (avg_len + 1e-5)

    words = re.findall(r"\b[a-zA-ZáéíóúÁÉÍÓÚñÑüÜ]+\b", text.lower())
    n_words = len(words)
    unique_words = len(set(words))
    ttr = (unique_words / n_words) if n_words > 0 else 0  # Type-Token Ratio

    # Check AI Buzzwords
    buzzword_matches = []
    for pattern in AI_BUZZWORDS:
        for m in re.finditer(pattern, text, flags=re.IGNORECASE):
            buzzword_matches.append(f"'{m.group(0)}'")
    buzzword_matches = list(set(buzzword_matches))

    # Check structural symmetry in lists
    bullet_lines = [line.strip() for line in text.split("\n") if line.strip().startswith(("-", "*", "1.", "2.", "3.", "4.", "5."))]
    symmetric_bullets = False
    if len(bullet_lines) >= 3:
        # Check if they all start with identical grammatical patterns
        first_words = [line.split()[1] if len(line.split()) > 1 else "" for line in bullet_lines]
        if len(set(first_words)) <= 2:
            symmetric_bullets = True

    # Risk assessment
    risk_factors = []
    if std_dev < 7.0:
        risk_factors.append(f"Baja variabilidad de longitud de oraciones (StdDev: {std_dev:.1f} palabras). Rango ideal humano: > 9.0.")
    if len(buzzword_matches) >= 3:
        risk_factors.append(f"Presencia de frases cliché de IA detectadas ({len(buzzword_matches)}): {', '.join(buzzword_matches[:5])}.")
    if ttr < 0.48 and n_words > 150:
        risk_factors.append(f"Baja riqueza léxica (TTR: {ttr:.2f}). Vocabulario muy predecible.")
    if symmetric_bullets:
        risk_factors.append("Estructura de listas simétrica y formulaica (patrón recurrente de IA).")

    risk_level = "BAJO (Parece Humano)"
    if len(risk_factors) >= 3:
        risk_level = "ALTO (Patrones claros de IA)"
    elif len(risk_factors) in (1, 2):
        risk_level = "MODERADO (Algunos marcadores detectables)"

    return {
        "stats": {
            "total_words": n_words,
            "total_sentences": n_sentences,
            "avg_sentence_length": round(avg_len, 1),
            "sentence_std_dev": round(std_dev, 1),
            "burstiness_index": round(burstiness_score, 2),
            "lexical_richness_ttr": round(ttr, 2),
        },
        "buzzwords_found": buzzword_matches,
        "risk_level": risk_level,
        "risk_factors": risk_factors,
        "sentences_preview": [(len(s.split()), s[:60] + "...") for s in sentences[:5]],
    }


def main():
    parser = argparse.ArgumentParser(description="Academic Style & AI Footprint Analyzer")
    parser.add_argument("file_path", nargs="?", help="Path to text or markdown file")
    parser.add_argument("--text", "-t", type=str, help="Raw text string to evaluate")

    args = parser.parse_args()
    text = ""

    if args.text:
        text = args.text
    elif args.file_path:
        with open(args.file_path, "r", encoding="utf-8") as f:
            text = f.read()
    else:
        # Read from stdin
        text = sys.stdin.read()

    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")

    result = analyze_text(text)
    if "error" in result:
        print(f"❌ Error al procesar el texto: {result['error']}")
        return

    print("=" * 65)
    print("📊 REPORTE DE ANÁLISIS DE ESTILO Y HUELLA DE IA (TURNITIN / GPTZERO)")
    print("=" * 65)
    st = result["stats"]
    print(f"• Palabras totales: {st['total_words']} | Oraciones: {st['total_sentences']}")
    print(f"• Longitud media: {st['avg_sentence_length']} palabras/oración")
    print(f"• Variabilidad de longitud (Burstiness / Desv. Estándar): {st['sentence_std_dev']} (Ideal: > 9.0)")
    print(f"• Riqueza léxica (TTR): {st['lexical_richness_ttr']} (Ideal: > 0.50)")
    print(f"\nNIVEL DE RIESGO DE DETECCIÓN: {result['risk_level']}")
    if result["risk_factors"]:
        print("\n⚠️ Factores de riesgo identificados:")
        for rf in result["risk_factors"]:
            print(f"  - {rf}")
    else:
        print("\n✅ El texto muestra ritmo natural, alta dispersión sintáctica y ausencia de clichés de IA.")
    print("=" * 65)


if __name__ == "__main__":
    main()
